// Pure function returning 100% genuine curated sets and words without any synthetic combinations
export function generateFullIeltsCorpus2000(): { sets: WordSet[]; words: VocabItem[] } {
  const words: VocabItem[] = [];
  const setsMap = new Map<string, WordSet>();

  // Initialize Sets from metadata
  TOPIC_SETS_METADATA.forEach((meta) => {
    setsMap.set(meta.id, {
      id: meta.id,
      title: meta.title,
      description: meta.description,
      sourceType: 'default',
      mainTopic: meta.mainTopic,
      topics: [meta.mainTopic],
      createdAt: Date.now() - 86400000 * 3,
      totalWords: 0,
      tags: meta.tags,
    });
  });

  // Populate Hand-curated Authentic Entries Only
  RAW_IELTS_2000_DATABASE.forEach((item, index) => {
    words.push({
      id: `voc-gold-${index + 1}`,
      term: item.term,
      ipa: item.ipa,
      meaning: item.meaning,
      wordFamily: item.wordFamily,
      synonyms: item.synonyms,
      antonyms: item.antonyms,
      example: item.example,
      notes: item.notes,
      sourceSetId: item.setId,
      cefrLevel: item.cefrLevel,
      targetIeltsBand: item.targetIeltsBand,
      topic: item.topic,
      mastery: 'new',
      srsStage: 0,
      nextReviewDate: Date.now(),
      reviewCount: 0,
      correctCount: 0,
      incorrectCount: 0,
      isBookmarked: false,
      isUnlearned: false,
    });
  });

  // Calculate actual set total counts based on genuine words
  const sets = Array.from(setsMap.values())
    .map((set) => {
      const total = words.filter((w) => w.sourceSetId === set.id).length;
      return {
        ...set,
        totalWords: total,
      };
    })
    .filter((set) => set.totalWords > 0);

  return { sets, words };
}
